  구름많음: '구름 한가득',
  흐림: '흐린 하늘',

  // 비 — 세기 순서: 빗방울 < 빗줄기
  소나기: '빗방울',
  실비: '보슬비', // light rain. API 가 자주 쓰는 표기입니다
