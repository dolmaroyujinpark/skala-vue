/* 키는 공백을 뺀 형태로 적습니다 — 아래 toFriendlyStatus 가 조회 전에
   공백을 지우기 때문입니다. API 가 '실 비' 로 주든 '실비' 로 주든,
   '구름 조금' 이든 '구름조금' 이든 같은 칸을 찾아갑니다.
   OpenWeatherMap 의 한글 표기가 띄어쓰기까지 일정하지 않아서 넣은 장치입니다. */
